#!/usr/bin/env python3
"""Generates lib/src/analysis/pinyin_initials.dart: the onset class of every
GB2312 character, derived from pypinyin (MIT License).

    pip install pypinyin
    python tools/reference/make_pinyin_table.py lib/src/analysis/pinyin_initials.dart

Classes (Mandarin initials, first/most common reading):
  unvoiced: b p f d t g k h j q x zh ch sh z c s  -> a silent/noisy gap before the vowel
  voiced:   m n l r                               -> continuous voicing with a level dip
  (others: vowel / y / w onsets, the default)
"""
import sys

from pypinyin import Style, pinyin

UNVOICED = {'b', 'p', 'f', 'd', 't', 'g', 'k', 'h', 'j', 'q', 'x', 'zh', 'ch', 'sh', 'z', 'c', 's'}
VOICED = {'m', 'n', 'l', 'r'}


def gb2312_chars():
    for hi in range(0xB0, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                yield bytes([hi, lo]).decode('gb2312')
            except UnicodeDecodeError:
                pass


def main(out):
    unvoiced, voiced = [], []
    for ch in gb2312_chars():
        ini = pinyin(ch, style=Style.INITIALS, strict=False, heteronym=False)[0][0]
        if ini in UNVOICED:
            unvoiced.append(ch)
        elif ini in VOICED:
            voiced.append(ch)

    def chunks(s, n=60):
        return [s[i:i + n] for i in range(0, len(s), n)]

    with open(out, 'w', encoding='utf-8') as f:
        f.write('// GENERATED by tools/reference/make_pinyin_table.py from pypinyin (MIT).\n')
        f.write('// Do not edit by hand.\n\n')
        f.write('/// How a sung syllable starts, from its Mandarin initial.\n')
        f.write('enum OnsetClass {\n')
        f.write('  /// b p f d t g k h j q x zh ch sh z c s: a voiceless consonant gap.\n  unvoiced,\n\n')
        f.write('  /// m n l r: voicing continues, the level dips.\n  voiced,\n\n')
        f.write('  /// Vowel, y- or w- onsets: often only a pitch or timbre change.\n  vowel,\n\n')
        f.write('  /// Not a known Chinese character (e.g. a Latin word).\n  unknown,\n}\n\n')
        for name, chars in (('_unvoiced', unvoiced), ('_voiced', voiced)):
            f.write(f'const {name} =\n')
            parts = chunks(''.join(chars))
            for i, p in enumerate(parts):
                f.write(f"    '{p}'{';' if i == len(parts) - 1 else ''}\n")
            f.write('\n')
        f.write('final Map<int, OnsetClass> _table = () {\n')
        f.write('  final m = <int, OnsetClass>{};\n')
        f.write('  for (final r in _unvoiced.runes) {\n    m[r] = OnsetClass.unvoiced;\n  }\n')
        f.write('  for (final r in _voiced.runes) {\n    m[r] = OnsetClass.voiced;\n  }\n')
        f.write('  return m;\n}();\n\n')
        f.write('bool _isCjk(int r) => (r >= 0x4E00 && r <= 0x9FFF) || (r >= 0x3400 && r <= 0x4DBF);\n\n')
        f.write('/// Onset class of a lyric token (a single character or a word).\n')
        f.write('OnsetClass onsetClassOf(String token) {\n')
        f.write('  if (token.isEmpty) return OnsetClass.unknown;\n')
        f.write('  final r = token.runes.first;\n')
        f.write('  final c = _table[r];\n')
        f.write('  if (c != null) return c;\n')
        f.write('  return _isCjk(r) ? OnsetClass.vowel : OnsetClass.unknown;\n}\n')
    print(f'{len(unvoiced)} unvoiced, {len(voiced)} voiced -> {out}')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else 'lib/src/analysis/pinyin_initials.dart')

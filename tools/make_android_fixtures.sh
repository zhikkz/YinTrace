#!/usr/bin/env bash
# Writes integration_test/android_fixtures.dart: short AAC files for the
# Android smoke test, embedded because the test runs on the device.
#   onset.m4a  44.1 kHz stereo, 0.5 s of silence, then 1 s of 440 Hz
#   tone.aac   48 kHz mono ADTS, 0.5 s of 660 Hz
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
ffmpeg -loglevel error -y -f lavfi \
  -i "aevalsrc=if(gte(t\,0.5)\,0.5*sin(2*PI*440*t)\,0)|if(gte(t\,0.5)\,0.5*sin(2*PI*440*t)\,0):s=44100:d=1.5" \
  -c:a aac -b:a 64k -map_metadata -1 -fflags +bitexact -flags:a +bitexact "$TMP/onset.m4a"
ffmpeg -loglevel error -y -f lavfi -i "aevalsrc=0.5*sin(2*PI*660*t):s=48000:d=0.5" \
  -c:a aac -b:a 48k -map_metadata -1 -fflags +bitexact -flags:a +bitexact -f adts "$TMP/tone.aac"
{
  echo "// Generated by tools/make_android_fixtures.sh. Do not edit."
  echo
  for name in onset.m4a tone.aac; do
    var="$(echo "$name" | sed -E 's/\.(m4a|aac)$//')$( [ "${name##*.}" = m4a ] && echo M4a || echo Aac )"
    echo "const ${var} ="
    base64 -w 100 "$TMP/$name" | sed -e "s/^/    '/" -e "s/\$/'/"
    echo "    ;"
    echo
  done
} > "$ROOT/integration_test/android_fixtures.dart"

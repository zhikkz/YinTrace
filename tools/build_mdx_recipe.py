#!/usr/bin/env python3
"""Make the weight-free copy recipe for Voc_FT's dynamic time axis.

Only ModelProto.graph.{input,output}.type.tensor_type.shape.dim[3]
changes: dim_value=256 (08 80 02) -> dim_param='T' (12 01 54).
Locate fields structurally, never by searching weight bytes. Both encodings
have the same length, so no enclosing protobuf lengths need updating.
"""
import argparse
import hashlib
import json
from pathlib import Path

from build_karaoke_graph import _fields, assemble

SOURCE_SHA = '534b2070fcc7df514b13ef660dc8cbb328679c2374d04354a5c42bb14ecce111'
SOURCE_NAME = 'UVR-MDX-NET-Voc_FT.onnx'
OUTPUT_NAME = 'UVR-MDX-NET-Voc_FT-dynamic.onnx'
ASSETS = Path(__file__).resolve().parent.parent / 'assets/models'


def children(buf, start, end, number):
    return [(s, e) for f, w, s, e in _fields(buf, start, end) if f == number and w == 2]


def time_dimensions(buf):
    graph, = children(buf, 0, len(buf), 7)
    offsets = []
    for field in (11, 12):  # GraphProto.input/output
        value, = children(buf, *graph, field)
        typ, = children(buf, *value, 2)
        tensor, = children(buf, *typ, 1)
        shape, = children(buf, *tensor, 2)
        dims = children(buf, *shape, 1)
        if len(dims) != 4:
            raise ValueError('expected a rank-4 tensor')
        start, end = dims[3]
        if buf[start:end] != b'\x08\x80\x02':
            raise ValueError('expected dim_value=256')
        offsets.append(start)
    return sorted(offsets)


def build(source, out_dir):
    buf = source.read_bytes()
    if hashlib.sha256(buf).hexdigest() != SOURCE_SHA:
        raise ValueError('not the official Voc_FT model')
    offsets = time_dimensions(buf)
    patched = bytearray(buf)
    graph = b'\x12\x01T' * len(offsets)
    segments = []
    cursor = 0
    literal = 0
    for offset in offsets:
        segments.append([literal, cursor, offset - cursor])
        patched[offset:offset + 3] = b'\x12\x01T'
        cursor = offset + 3
        literal = 3
    segments.append([literal, cursor, len(buf) - cursor])
    recipe = {
        'format': 'yintrace-model-recipe', 'version': 1,
        'about': 'Dynamic time axis only; no weights. Generated by tools/build_mdx_recipe.py.',
        'source': {'name': SOURCE_NAME, 'bytes': len(buf), 'sha256': SOURCE_SHA},
        'output': {'name': OUTPUT_NAME, 'bytes': len(patched), 'sha256': hashlib.sha256(patched).hexdigest()},
        'graph': {'bytes': len(graph), 'sha256': hashlib.sha256(graph).hexdigest()},
        'patchOffsets': offsets,
        'input': {'name': 'input', 'shape': [1, 4, 3072, 'T']},
        'outputName': 'output', 'segments': segments,
    }
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / 'mdx_graph.bin').write_bytes(graph)
    (out_dir / 'mdx_graph.json').write_text(json.dumps(recipe, separators=(',', ':')) + '\n')
    return recipe, graph


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('source', type=Path)
    ap.add_argument('--out-dir', type=Path, default=ASSETS)
    ap.add_argument('--out', type=Path, help='also assemble here (never commit the model)')
    args = ap.parse_args()
    recipe, graph = build(args.source, args.out_dir)
    if args.out:
        assemble(recipe, graph, args.source, args.out)
        assert hashlib.sha256(args.out.read_bytes()).hexdigest() == recipe['output']['sha256']
    print(json.dumps({k: recipe[k] for k in ('patchOffsets', 'output')}, indent=2))


if __name__ == '__main__':
    main()
